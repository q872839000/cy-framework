package com.cy.mq.core;

/**
 * MQ 消息投递模式。
 * <p>
 * 该枚举描述消息在底层驱动中的投递语义，属于通用 MQ 能力，不绑定任何业务组件。
 * 不同驱动可以按自身能力选择支持全部或部分模式；不支持的驱动应优雅降级为默认行为。
 * </p>
 *
 * @author pcy
 * @date 2026/04/14
 */
public enum MqDeliveryMode {

    /**
     * 使用驱动默认投递策略。
     */
    DEFAULT,

    /**
     * 仅使用发布/订阅语义投递。
     */
    PUBSUB,

    /**
     * 仅使用可消费组回放的流式语义投递。
     */
    STREAM,

    /**
     * 同时使用发布/订阅与流式语义投递。
     */
    BOTH
}
